import type { FareIndex, FareRange, VariantFares } from '@/lib/eta/fares/types'

function isFareRange(value: unknown): value is FareRange {
  return (
    Array.isArray(value) &&
    value.length === 2 &&
    Number.isInteger(value[0]) &&
    value[0] >= 0 &&
    typeof value[1] === 'number' &&
    Number.isFinite(value[1]) &&
    value[1] >= 0
  )
}

function isVariantFares(value: unknown): value is VariantFares {
  if (typeof value !== 'object' || value === null) return false
  const record = value as Record<string, unknown>
  if (!Array.isArray(record.stops) || !record.stops.every((stop) => typeof stop === 'string')) {
    return false
  }
  if (!Array.isArray(record.fares) || record.fares.length !== record.stops.length) return false
  return record.fares.every(
    (ranges) => ranges === null || (Array.isArray(ranges) && ranges.every(isFareRange))
  )
}

function isFareIndex(value: unknown): value is FareIndex {
  if (typeof value !== 'object' || value === null) return false
  const record = value as Record<string, unknown>
  if (typeof record.updated !== 'string') return false
  if (typeof record.variants !== 'object' || record.variants === null) return false
  const variants = Object.values(record.variants as Record<string, unknown>)
  // Every range walk is the expensive part. The file is generated by our
  // own script and `real-file.test.ts` validates it in depth, so production
  // checks the shape that would break lookup: parallel stops/fares arrays.
  if (process.env.NODE_ENV === 'production') {
    return variants.every((variant) => {
      if (typeof variant !== 'object' || variant === null) return false
      const entry = variant as Record<string, unknown>
      return (
        Array.isArray(entry.stops) &&
        Array.isArray(entry.fares) &&
        entry.stops.length === entry.fares.length
      )
    })
  }
  return variants.every(isVariantFares)
}

let resolvedCache: FareIndex | null | undefined
let inflight: Promise<FareIndex | null> | undefined

/**
 * Load the prebuilt origin/destination fare matrix from same-origin static
 * JSON. Module-singleton in-flight + resolved cache. Never throws: on any
 * error (network, parse, shape) returns null and the UI keeps its existing
 * boarding-stop fare fallback.
 */
export function loadFareIndex(): Promise<FareIndex | null> {
  if (resolvedCache !== undefined) return Promise.resolve(resolvedCache)
  if (inflight) return inflight
  inflight = (async () => {
    try {
      const res = await fetch('/fares/fares.json', { cache: 'force-cache' })
      if (!res.ok) return null
      const json: unknown = await res.json()
      return isFareIndex(json) ? json : null
    } catch {
      return null
    }
  })()
  return inflight.then((index) => {
    // Do not cache a failed load: a later mount gets another attempt.
    if (index) resolvedCache = index
    inflight = undefined
    return index
  })
}

/** Test hook: clear the module-singleton cache. */
export function __resetFareIndexCacheForTests(): void {
  resolvedCache = undefined
  inflight = undefined
}
